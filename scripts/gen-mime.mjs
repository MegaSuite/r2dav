// Generates the extension -> MIME map used by both the web app and Pages
// Functions. The map is checked in so runtime does not need `mime-db`.
//
// Usage: node scripts/gen-mime.mjs
//        node scripts/gen-mime.mjs --check

import { createRequire } from "node:module";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const db = require("mime-db");

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const targets = [
  resolve(root, "src/shared/mime-map.ts"),
  resolve(root, "functions/lib/mime-map.ts"),
];

// mime-db is ordered by MIME type, not by extension. Resolve conflicts with an
// explicit preference list, then prefer more specific/known types.
const PREFERRED = {
  // Text / config / code
  txt: "text/plain",
  text: "text/plain",
  log: "text/plain",
  md: "text/markdown",
  markdown: "text/markdown",
  yaml: "text/yaml",
  yml: "text/yaml",
  toml: "application/toml",
  ini: "text/plain",
  conf: "text/plain",
  cfg: "text/plain",
  env: "text/plain",
  properties: "text/plain",
  ovpn: "text/plain",
  csv: "text/csv",
  tsv: "text/tab-separated-values",
  json: "application/json",
  jsonc: "application/json",
  json5: "application/json",
  xml: "application/xml",
  xsl: "application/xml",
  xslt: "application/xml",
  html: "text/html",
  htm: "text/html",
  css: "text/css",
  js: "text/javascript",
  mjs: "text/javascript",
  cjs: "text/javascript",
  jsx: "text/javascript",
  ts: "text/plain", // TypeScript source by default; video/mp2t wins if stored.
  tsx: "text/plain",
  sh: "text/x-shellscript",
  bash: "text/x-shellscript",
  zsh: "text/x-shellscript",
  fish: "text/x-shellscript",
  ps1: "text/plain",
  bat: "text/plain",
  cmd: "text/plain",
  sql: "application/sql",
  graphql: "application/graphql",
  gql: "application/graphql",
  diff: "text/plain",
  patch: "text/plain",
  srt: "text/plain",
  vtt: "text/vtt",
  tex: "text/plain",
  lock: "text/plain",

  // Calendar / contacts
  ics: "text/calendar",
  ical: "text/calendar",
  vcf: "text/vcard",
  vcard: "text/vcard",

  // Web / image
  svg: "image/svg+xml",
  png: "image/png",
  jpg: "image/jpeg",
  jpeg: "image/jpeg",
  gif: "image/gif",
  webp: "image/webp",
  avif: "image/avif",
  bmp: "image/bmp",
  ico: "image/x-icon",
  tif: "image/tiff",
  tiff: "image/tiff",

  // Documents / archives / fonts
  pdf: "application/pdf",
  zip: "application/zip",
  tar: "application/x-tar",
  gz: "application/gzip",
  tgz: "application/gzip",
  bz2: "application/x-bzip2",
  xz: "application/x-xz",
  zst: "application/zstd",
  "7z": "application/x-7z-compressed",
  rar: "application/vnd.rar",
  woff: "font/woff",
  woff2: "font/woff2",
  ttf: "font/ttf",
  otf: "font/otf",
  eot: "application/vnd.ms-fontobject",
  wasm: "application/wasm",
};

const MIME_PRIORITY = [
  (mime) => mime.startsWith("text/"),
  (mime) => mime === "application/json",
  (mime) => mime === "application/xml",
  (mime) => mime.startsWith("image/"),
  (mime) => mime.startsWith("audio/"),
  (mime) => mime.startsWith("video/"),
  (mime) => mime.startsWith("font/"),
  (mime) => mime.startsWith("application/"),
];

function score(mime) {
  const index = MIME_PRIORITY.findIndex((predicate) => predicate(mime));
  return index === -1 ? MIME_PRIORITY.length : index;
}

const byExt = {};
for (const [mime, meta] of Object.entries(db)) {
  if (mime === "application/octet-stream") continue;
  for (const rawExt of meta.extensions ?? []) {
    const ext = rawExt.toLowerCase().replace(/^\./, "");
    if (!ext) continue;
    const current = byExt[ext];
    if (!current || score(mime) < score(current)) byExt[ext] = mime;
  }
}
for (const [ext, mime] of Object.entries(PREFERRED)) byExt[ext] = mime;

const charset = {};
for (const [mime, meta] of Object.entries(db)) {
  if (meta.charset) charset[mime] = meta.charset;
}
// Ensure common textual types get a charset even if mime-db omits it.
for (const mime of Object.values(PREFERRED)) {
  if (
    mime.startsWith("text/") ||
    ["application/json", "application/xml", "application/toml", "application/yaml"].includes(mime)
  ) {
    charset[mime] = charset[mime] || "UTF-8";
  }
}

const sortedExt = Object.fromEntries(
  Object.entries(byExt).sort(([a], [b]) => a.localeCompare(b))
);
const sortedCharset = Object.fromEntries(
  Object.entries(charset).sort(([a], [b]) => a.localeCompare(b))
);

const source = `// Generated by scripts/gen-mime.mjs. Do not edit by hand.
// Source: mime-db. Run \`npm run gen:mime\` after changing dependencies.

export const MIME_BY_EXT: Record<string, string> = ${JSON.stringify(sortedExt, null, 2)};

export const CHARSET_BY_MIME: Record<string, string> = ${JSON.stringify(
  sortedCharset,
  null,
  2
)};
`;

let failed = false;
for (const target of targets) {
  mkdirSync(dirname(target), { recursive: true });
  if (process.argv.includes("--check")) {
    let existing = "";
    try {
      existing = readFileSync(target, "utf8");
    } catch {
      // Missing generated file counts as a failure.
    }
    if (existing !== source) {
      failed = true;
      console.error(`out of date: ${target}`);
    }
  } else {
    writeFileSync(target, source);
    console.log(`wrote ${target}`);
  }
}

if (failed) {
  console.error("MIME map is out of date. Run: npm run gen:mime");
  process.exit(1);
}
